"""Build index.html (searchable list) and map.html (pipeline map) from data/.
Usage: python3 build.py"""
import json, pathlib

here = pathlib.Path(__file__).parent
data = json.loads((here / "data" / "conference-resources-2026.json").read_text())
ins = json.loads((here / "data" / "map-insights.json").read_text())
blob = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
(here / "index.html").write_text((here / "template.html").read_text().replace("/*DATA*/null", blob))
(here / "map.html").write_text((here / "template-map.html").read_text().replace("/*DATA*/null", blob)
                               .replace("/*INSIGHTS*/[]", json.dumps(ins, ensure_ascii=False)))
import collections
R = data["items"]
T = [("skill","Skills, prompts and agent instructions"),("model","Models"),("dataset","Datasets and corpora"),("archive","Archives and collections"),("benchmark","Benchmarks"),("tool","Tools and platforms"),("method","Methods (training, adaptation, workflow)"),("paper","Papers")]
c = collections.Counter(r["type"] for r in R); o = collections.Counter(r["open"] for r in R)
L = ["---", 'title: "Ars Inquirendi 2026: skills, models, datasets, tools, methods and papers"', "source: data/conference-resources-2026.json (generated by build.py)", "---", "",
     "# Ars Inquirendi 2026: what participants named", "",
     f"{len(R)} distinct items from all three days. By type: " + ", ".join(f"{n} {c[t]}" for t, n in T) + ". Openness: " + ", ".join(f"{k} {v}" for k, v in o.most_common()) + ".", "",
     "Searchable version: index.html. Pipeline map: map.html. Links were found by web search and not checked by a person.", ""]
for t, n in T:
    rs = sorted([r for r in R if r["type"] == t], key=lambda r: (str(r["subtype"]).lower(), r["name"].lower()))
    if not rs: continue
    L += [f"## {n} ({len(rs)})", ""]
    for r in rs:
        who = "; ".join(dict.fromkeys(f"{m['who']} ({m['day']})" for m in r["mentions"]))
        url = r["url"] if r["url"] and r["url"] != "not found" else "no public link found"
        L.append(f"- **{r['name']}** · {r['subtype']} · {r['open']}, {r['confidence']}. {r['what']} *Used by:* {who}. {url}")
    L.append("")
(here / "resources.md").write_text("\n".join(L))
print("wrote index.html and map.html,", len(data["items"]), "items")
